// Small line icons drawn inline (no icon font or image host, so nothing new for the security policy). They take the
// text colour, and are hidden from screen readers: the button or link around each one carries the words.
function Icon({ children, size = 22 }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

